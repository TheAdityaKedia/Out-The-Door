"""Render DejaVu Sans into Adafruit GFX font headers for the firmware.

    python3 tools/make_fonts.py [folder with DejaVuSans*.ttf]

Writes lib/core/fonts/*.h. Each font covers printable ASCII plus the degree
sign (0xB0), and records its ascent so text can be placed by its top edge,
the way the mockups were drawn. Needs Pillow.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "lib", "core", "fonts")
SEARCH = [sys.argv[1]] if len(sys.argv) > 1 else [
    "/usr/share/fonts/truetype/dejavu",
    "/Library/Fonts",
    os.path.expanduser("~/Library/Fonts"),
]
FIRST, LAST = 0x20, 0xB0
WANTED = set(range(0x20, 0x7F)) | {0xB0}

# name -> (font file, pixel size)
FONTS = {
    "Bold10": ("DejaVuSans-Bold.ttf", 10),
    "Sans10": ("DejaVuSans.ttf", 10),
    "Sans11": ("DejaVuSans.ttf", 11),
    "Bold12": ("DejaVuSans-Bold.ttf", 12),
    "Bold14": ("DejaVuSans-Bold.ttf", 14),
    "Bold16": ("DejaVuSans-Bold.ttf", 16),
    "Bold17": ("DejaVuSans-Bold.ttf", 17),
    "Bold18": ("DejaVuSans-Bold.ttf", 18),
    "Bold26": ("DejaVuSans-Bold.ttf", 26),
    "Bold30": ("DejaVuSans-Bold.ttf", 30),
}


def find(name):
    for d in SEARCH:
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    sys.exit("Can't find %s; pass the folder that holds the DejaVu fonts." % name)


def render(font, ch, ascent):
    # Draw on a roomy canvas with the baseline at a known row, then crop to ink.
    pad = 8
    size = (font.size * 3, font.size * 3)
    im = Image.new("1", size, 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((pad, pad), ch, font=font, fill=1)  # top-left of the ascent box
    baseline = pad + ascent
    box = im.getbbox()
    advance = int(round(font.getlength(ch)))
    if box is None:
        return advance, 0, 0, 0, 0, b""
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    px = im.load()
    bits = []
    for y in range(y0, y1):
        for x in range(x0, x1):
            bits.append(1 if px[x, y] else 0)
    data = bytearray((len(bits) + 7) // 8)
    for i, b in enumerate(bits):
        if b:
            data[i // 8] |= 0x80 >> (i % 8)
    return advance, w, h, x0 - pad, y0 - baseline, bytes(data)


def build(name, path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    bitmap, glyphs = bytearray(), []
    for code in range(FIRST, LAST + 1):
        if code in WANTED:
            adv, w, h, xo, yo, data = render(font, chr(code), ascent)
        else:
            adv, w, h, xo, yo, data = 0, 0, 0, 0, 0, b""
        glyphs.append((len(bitmap), w, h, adv, xo, yo, code))
        bitmap += data
    var = "DejaVu" + name
    lines = [
        "// Generated by tools/make_fonts.py from %s at %d px. Do not edit."
        % (os.path.basename(path), size),
        "// DejaVu fonts: Bitstream Vera license, see LICENSE-DejaVu.txt in this folder.",
        "#pragma once",
        "#include <Adafruit_GFX.h>",
        "",
        "const uint8_t %sBitmaps[] PROGMEM = {" % var,
    ]
    for i in range(0, len(bitmap), 16):
        lines.append("  " + ", ".join("0x%02X" % b for b in bitmap[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("const GFXglyph %sGlyphs[] PROGMEM = {" % var)
    for off, w, h, adv, xo, yo, code in glyphs:
        lines.append("  {%5d, %2d, %2d, %2d, %3d, %3d},  // 0x%02X" % (off, w, h, adv, xo, yo, code))
    lines.append("};")
    lines.append("")
    lines.append("const GFXfont %s PROGMEM = {(uint8_t *)%sBitmaps, (GFXglyph *)%sGlyphs, 0x%02X, 0x%02X, %d};"
                 % (var, var, var, FIRST, LAST, ascent + descent))
    lines.append("const int8_t %sAscent = %d;" % (var, ascent))
    with open(os.path.join(OUT, name + ".h"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for name, (fname, size) in FONTS.items():
        build(name, find(fname), size)
        print("wrote lib/core/fonts/%s.h" % name)

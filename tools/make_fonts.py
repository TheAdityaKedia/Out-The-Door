"""Convert DejaVu Sans into the small bitmap font modules the firmware uses.

Run on a laptop (needs Pillow):  python3 tools/make_fonts.py [path/to/fonts]
Each output module in firmware/fonts/ holds, per character, its advance width
and a 1-bit bitmap (MONO_HLSB, ink = 1) as tall as the font's line height, so
text drawn at y lands exactly where Pillow would draw it at y.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "firmware", "fonts")
SEARCH = [sys.argv[1]] if len(sys.argv) > 1 else [
    "/usr/share/fonts/truetype/dejavu",
    "/Library/Fonts",
    os.path.expanduser("~/Library/Fonts"),
]
CHARS = "".join(chr(c) for c in range(32, 127)) + "°"

# module name -> (font file, pixel size)
FONTS = {
    "bold10": ("DejaVuSans-Bold.ttf", 10),
    "sans10": ("DejaVuSans.ttf", 10),
    "sans11": ("DejaVuSans.ttf", 11),
    "bold12": ("DejaVuSans-Bold.ttf", 12),
    "bold14": ("DejaVuSans-Bold.ttf", 14),
    "bold16": ("DejaVuSans-Bold.ttf", 16),
    "bold17": ("DejaVuSans-Bold.ttf", 17),
    "bold18": ("DejaVuSans-Bold.ttf", 18),
    "bold26": ("DejaVuSans-Bold.ttf", 26),
    "bold30": ("DejaVuSans-Bold.ttf", 30),
}


def find(name):
    for d in SEARCH:
        p = os.path.join(d, name)
        if os.path.exists(p):
            return p
    sys.exit("Can't find %s; pass the folder that holds DejaVu fonts." % name)


def glyph(font, ch, height):
    w = max(1, int(round(font.getlength(ch))))
    im = Image.new("1", (w, height), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"
    d.text((0, 0), ch, font=font, fill=1)
    row_bytes = (w + 7) // 8
    data = bytearray(row_bytes * height)
    px = im.load()
    for y in range(height):
        for x in range(w):
            if px[x, y]:
                data[y * row_bytes + x // 8] |= 0x80 >> (x % 8)
    return w, bytes(data)


def build(mod, path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    height = ascent + descent
    lines = [
        "# Generated by tools/make_fonts.py from %s at %d px. Do not edit."
        % (os.path.basename(path), size),
        "# DejaVu fonts: Bitstream Vera license, see fonts/LICENSE-DejaVu.txt",
        "HEIGHT = %d" % height,
        "ASCENT = %d" % ascent,
        "GLYPHS = {",
    ]
    for ch in CHARS:
        w, data = glyph(font, ch, height)
        lines.append("    %r: (%d, %r)," % (ch, w, data))
    lines.append("}")
    with open(os.path.join(OUT, mod + ".py"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    for mod, (fname, size) in FONTS.items():
        build(mod, find(fname), size)
        print("wrote fonts/%s.py" % mod)
